/*
 * docs.mjs — the glossary, written out where people read it. Node only.
 *
 * The Info pages on the Move take their definitions from TERMS in info.mjs.
 * The same definitions go into two more places — the Terms page of help.json,
 * which Schwung's Help viewer shows, and the glossary table in the README — so
 * they are generated here from that one source rather than kept by hand in
 * three. `npm run docs` writes them; tests/docs.test.mjs fails if either is
 * out of date.
 *
 * The curriculum is written out the same way: docs/curriculum.md is made from
 * curriculum.mjs, the data the Path follows and its Info pages
 * read, so the page people read is always the path the Move teaches.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { TERMS, wrapLines } from '../src/info.mjs';
import { buildProgram } from '../src/program.mjs';
import { PATH_TEXT, STRANDS, STRAND_TEXT } from '../src/curriculum.mjs';
import { parseManifest, parseExercise } from '../src/exercise_io.mjs';
import { INFO_TEXT_PX } from '../src/layout.mjs';
import { createScreen } from './screen_buffer.mjs';

/* Help pages are read on the panel, beside its scrollbar: every line, these
 * and the hand-written ones, fits INFO_TEXT_PX in the panel's own font. */
const measure = createScreen();
export const helpLineFits = (line) => measure.textWidth(line) <= INFO_TEXT_PX;
export const README_START = '<!-- glossary:start (generated by npm run docs) -->';
export const README_END = '<!-- glossary:end -->';

export function termsPage() {
  const lines = [];
  for (const key of Object.keys(TERMS)) {
    const [name, text] = TERMS[key];
    if (lines.length) lines.push('');
    lines.push(name);
    const body = wrapLines([{ text, head: false }], INFO_TEXT_PX, (s) => measure.textWidth('  ' + s));
    for (const l of body) lines.push('  ' + l.text);
  }
  return { title: 'Terms', lines };
}

/* help.json with its Terms page replaced, or added at the end. */
export function helpWithTerms(help) {
  const page = termsPage();
  const children = help.children.filter((c) => c.title !== 'Terms').concat([page]);
  return { ...help, children };
}

export function glossaryTable() {
  const rows = Object.keys(TERMS).map((k) => '| **' + TERMS[k][0] + '** | ' + TERMS[k][1] + ' |');
  return ['| Term | Meaning |', '| --- | --- |'].concat(rows).join('\n');
}

export function readmeWithGlossary(readme) {
  const a = readme.indexOf(README_START);
  const b = readme.indexOf(README_END);
  if (a < 0 || b < a) throw new Error('README has no glossary markers');
  return readme.slice(0, a + README_START.length) + '\n' + glossaryTable() + '\n' + readme.slice(b);
}

/* ---- The curriculum ------------------------------------------------------- */

const cell = (text) => String(text || '').replace(/\|/g, '\\|');

function bundledSongs() {
  const dir = new URL('../src/exercises/', import.meta.url);
  const text = readFileSync(new URL('index.json', dir), 'utf8');
  return parseManifest(text).map((row) => ({
    chart: parseExercise(readFileSync(new URL(row.file, dir), 'utf8'), row.id).chart,
    category: row.category,
  }));
}

export function curriculumMarkdown(phases) {
  const unitByKey = {};
  for (const p of phases) for (const u of p.units) unitByKey[u.key] = u;
  const out = [
    '# The Learning Path',
    '',
    '<!-- generated by npm run docs from src/curriculum.mjs; edit that file, not this one -->',
    '',
    PATH_TEXT.intro, '', PATH_TEXT.adults, '', PATH_TEXT.order, '', PATH_TEXT.free, '', PATH_TEXT.stages, '',
    '## How the path follows you', '', PATH_TEXT.continue, '', PATH_TEXT.check, '',
    '## Strands', '',
    'Every unit trains one strand:', '',
  ];
  for (const k of Object.keys(STRANDS)) out.push('- **' + STRANDS[k] + '**: ' + STRAND_TEXT[k] + '.');
  for (const p of phases) {
    out.push('', '---', '', '## Stage ' + p.n + ': ' + p.title, '', '**Promise:** *' + p.promise + '*', '', '**The idea:** ' + p.idea);
    for (const u of p.units) {
      const after = u.after.map((k) => unitByKey[k] ? unitByKey[k].name : k);
      out.push('', '### ' + u.num + ' ' + u.name + ' (' + STRANDS[u.strand] + ')' + (after.length ? ' · after ' + after.join(', ') : ''),
        '', '*What it is for: ' + u.purpose.replace(/\.$/, '').replace(/^./, (c) => c.toLowerCase()) + '.*', '');
      if (u.summary) {
        out.push(u.summary, '', u.exercises.map((e) => e.label).join(' · '));
        continue;
      }
      out.push('| Exercise | What you do | Why it is there |', '|---|---|---|');
      for (const e of u.exercises) out.push('| ' + cell(e.label) + ' | ' + cell(e.about) + ' | ' + cell(e.why) + ' |');
    }
    if (p.check.length) {
      const names = p.check.map((id) => {
        for (const u of p.units) for (const e of u.exercises) if (e.steps.some((s) => s.id === id)) return e.label;
        return id;
      });
      out.push('', '**Checkpoint.** ' + names.join(', ') + ', each passed Solo.');
    }
  }
  out.push('', '---', '', '## Off the path', '', PATH_TEXT.offPath, '');
  return out.join('\n');
}

const HELP = new URL('../src/help.json', import.meta.url);
const README = new URL('../README.md', import.meta.url);
const CURRICULUM = new URL('../docs/curriculum.md', import.meta.url);

export function expected() {
  const help = JSON.stringify(helpWithTerms(JSON.parse(readFileSync(HELP, 'utf8'))), null, 2) + '\n';
  const readme = readmeWithGlossary(readFileSync(README, 'utf8'));
  const curriculum = curriculumMarkdown(buildProgram({ songs: bundledSongs() }));
  return { help, readme, curriculum };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { help, readme, curriculum } = expected();
  writeFileSync(HELP, help);
  writeFileSync(README, readme);
  writeFileSync(CURRICULUM, curriculum);
  console.log('help.json Terms page, README glossary and docs/curriculum.md written.');
}

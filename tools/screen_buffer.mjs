/*
 * screen_buffer.mjs — a desktop stand-in for the Move's 128x64 1-bit screen.
 *
 * NOT shipped to the device: it exists so staff_render.mjs can be rendered and
 * asserted on from `node --test`, and eyeballed as ASCII art from
 * `npm run preview`. It mimics the host primitives closely enough for layout
 * work — in particular a 5px glyph on a 6px advance, which is what the Move's
 * default font does and what text_width() reports.
 */


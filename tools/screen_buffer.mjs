export function createScreen() {
  const px = new Uint8Array(W * H);

  const set = (x, y, v) => {
    x |= 0;
    y |= 0;
    if (x < 0 || y < 0 || x >= W || y >= H) return;
    px[y * W + x] = v ? 1 : 0;
  };

  const ctx = {
    pixels: px,
    calls: 0,
    clear() {
      px.fill(0);
      this.calls++;
    },
    fillRect(x, y, w, h, v) {
      this.calls++;
      for (let yy = 0; yy < h; yy++) for (let xx = 0; xx < w; xx++) set(x + xx, y + yy, v);
    },
    drawRect(x, y, w, h, v) {
      this.calls++;
      for (let xx = 0; xx < w; xx++) {
        set(x + xx, y, v);
        set(x + xx, y + h - 1, v);
      }
      for (let yy = 0; yy < h; yy++) {
        set(x, y + yy, v);
        set(x + w - 1, y + yy, v);
      }
    },
    line(x0, y0, x1, y1, v) {
      this.calls++;
      /* Bresenham, same shape as the host's draw_line. */
      let dx = Math.abs(x1 - x0);
      let dy = -Math.abs(y1 - y0);
      let sx = x0 < x1 ? 1 : -1;
      let sy = y0 < y1 ? 1 : -1;
      let err = dx + dy;
      for (;;) {
        set(x0, y0, v);
        if (x0 === x1 && y0 === y1) break;
        const e2 = 2 * err;
        if (e2 >= dy) {
          err += dy;
          x0 += sx;
        }
        if (e2 <= dx) {
          err += dx;
          y0 += sy;
        }
      }
    },
    text(x, y, s, v) {
      this.calls++;
      let cx = x;
      for (let i = 0; i < s.length; i++) {
        const g = F[s[i]] || F[s[i].toUpperCase()] || F['?'];
        for (let row = 0; row < CHAR_H; row++) {
          const bits = g[row];
          for (let col = 0; col < 5; col++) {
            if (bits & (1 << (4 - col))) set(cx + col, y + row, v);
          }
        }
        cx += CHAR_W;
      }
    },
    textWidth(s) {
      return s.length * CHAR_W - 1;
    },
    fontHeight() {
      return CHAR_H;
    },
  };
  return ctx;
}

/* Render the buffer as ASCII art with a coordinate ruler. */
export function toAscii(ctx, { on = '#', off = '.', ruler = true } = {}) {
  const lines = [];
  if (ruler) {
    let tens = '    ';
    let ones = '    ';
    for (let x = 0; x < W; x++) {
      tens += x % 10 === 0 ? String(Math.floor(x / 10) % 10) : ' ';
      ones += String(x % 10);
    }
    lines.push(tens, ones);
  }
  for (let y = 0; y < H; y++) {
    let row = '';
    for (let x = 0; x < W; x++) row += ctx.pixels[y * W + x] ? on : off;
    lines.push(String(y).padStart(3, ' ') + ' ' + row);
  }
  return lines.join('\n');
}

/* Count lit pixels inside a rect — the workhorse for rendering assertions. */
export function countOn(ctx, x, y, w, h) {
  let n = 0;
  for (let yy = y; yy < y + h; yy++) {
    for (let xx = x; xx < x + w; xx++) {
      if (xx < 0 || yy < 0 || xx >= W || yy >= H) continue;
      if (ctx.pixels[yy * W + xx]) n++;
    }
  }
  return n;
}

export function isOn(ctx, x, y) {
  if (x < 0 || y < 0 || x >= W || y >= H) return false;
  return ctx.pixels[y * W + x] === 1;
}
